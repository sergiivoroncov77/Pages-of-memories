const CYRILLIC: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm',
  н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya', і: 'i', ї: 'yi', є: 'ye', ґ: 'g'
};

/**
 * A file name that survives every phone, messenger and download manager:
 * Latin letters, digits and dashes only (some browsers drop non-ASCII names).
 */
export function safeFileName(title: string, fallback = 'kniga'): string {
  const latin = [...title.toLocaleLowerCase('ru')].map((char) => CYRILLIC[char] ?? char).join('');
  const slug = latin.normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48).replace(/-+$/, '');
  return slug || fallback;
}
